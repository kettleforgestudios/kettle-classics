# 'Just right' zone of each seed type, in gauge levels (water / 8):
#   normal 3-5 (water 24-47), thirsty 4-6 (32-55), delicate 2-3 (16-31), Kip 3-4 (24-39).
# These must match the SeedTypes table in src/play.asm.
ZONES = [(3, 5), (4, 6), (2, 3), (3, 4)]


def gauge(level, zone=(3, 5)):
    # A little tube: walls at columns 2 and 5, water fills from the bottom.
    # Ticks on the right (column 6) mark the 'just right' zone (levels 3-5).
    rows = []
    for r in range(8):
        filled = (7 - r) < level
        inside = "--" if filled else ".."
        # Row r is the top of the water at level 8 - r, so the zone's ticks
        # sit on rows 8-(high+1) .. 8-(low+1).
        low, high = zone
        tick = "+" if 7 - high <= r <= 7 - low else "."
        rows.append(".." + "#" + inside + "#" + tick + ".")
    return rows

COL = {'.':'0', '-':'1', '+':'2', '#':'3'}


def row(text):
    return "`" + "".join(COL[c] for c in text.ljust(8, '.'))


def tile(lines, out, label):
    out.append(f"    ; {label}")
    for r in (lines + ["........"] * 8)[:8]:
        out.append("    dw " + row(r))


def big(lines, out, name):
    parts = [("top-left", 0, 0), ("top-right", 0, 8), ("bottom-left", 8, 0), ("bottom-right", 8, 8)]
    for label, y, x in parts:
        tile([l[x:x + 8] for l in lines[y:y + 8]], out, f"{name} {label}")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "..", "src")
    order = "".join(sorted(FONT))
    out = ["; GENERATED by art/make_gfx.py - edit the art there, then re-run it.",
           "; Original Kettle Forge Studios pixel art (font, Kip, cloud, water, soil, seeds, sun, crow).",
           "", 'SECTION "Graphics", ROM0', "", "Tiles::", "    ; tile 0: blank", "    ds 16, 0"]
    for ch in order:
        tile(FONT[ch], out, f"letter {ch}")
    n = len(order) + 1
    consts = {}
    consts["TILE_KIP"] = n;      big(KIP, out, "Kip");      n += 4
    consts["TILE_CLOUD"] = n;    big(CLOUD, out, "cloud");  n += 4
    consts["TILE_DROP"] = n;     tile(DROP, out, "water drop");  n += 1
    consts["TILE_SOIL_TOP"] = n; tile(SOIL_TOP, out, "soil surface"); n += 1
    consts["TILE_SOIL"] = n;     tile(SOIL, out, "soil");   n += 1
    # Growing seeds, one picture per type (order = TYPE_ numbers in main.asm).
    consts["TILE_SEED_TYPES"] = n
    for name, art in (("normal seed", SEED), ("thirsty seed", THIRSTY),
                      ("delicate seed", DELICATE), ("Kip's seed", KIP_SEED)):
        tile(art, out, name); n += 1
    # Finished seeds, in SEED_ state order (1 sprouted ... 4 stolen).
    consts["TILE_SPROUT"] = n
    for name, art in (("sprout", SPROUT), ("wilted", WILTED), ("flooded", FLOODED),
                      ("stolen by a crow", STOLEN)):
        tile(art, out, name); n += 1
    # Thirst gauges: 8 levels for each seed type (the ticks show its zone).
    consts["TILE_GAUGE"] = n
    for t, zone in enumerate(ZONES):
        for level in range(8):
            tile(gauge(level, zone), out, f"thirst gauge, type {t}, level {level}"); n += 1
    consts["TILE_SUN"] = n;      big(SUN, out, "sun");       n += 4
    consts["TILE_CROW"] = n;     big(CROW_UP, out, "crow wings up"); n += 4
    big(CROW_DOWN, out, "crow wings down"); n += 4
    consts["TILE_BLOCK"] = n;    tile(BLOCK, out, "solid block"); n += 1
    out += ["TilesEnd::", ""]
    open(os.path.join(src, "gfx.asm"), "w").write("\n".join(out))

    cm = ["; GENERATED by art/make_gfx.py. Text characters -> font tile numbers, plus tile numbers.",
          'CHARMAP " ", 0']
    cm += [f'CHARMAP "{ch}", {order.index(ch) + 1}' for ch in order]
    cm += [f"DEF {k} EQU {v}" for k, v in consts.items()]
    cm.append(f"DEF TILE_DIGIT0 EQU {order.index('0') + 1}")
    cm.append(f"DEF TILE_ARROW_R EQU {order.index('>') + 1}")
    cm.append(f"DEF TILE_ARROW_L EQU {order.index('<') + 1}")
    open(os.path.join(src, "charmap.inc"), "w").write("\n".join(cm) + "\n")
    print("tiles:", n, consts)


if __name__ == "__main__":
    main()
