#!/usr/bin/env python3
"""Writes src/notes.inc: the pitch numbers for musical notes on the Pocket sound chip.

Run:  python3 art/make_notes.py

The chip doesn't take notes in Hz; it takes an 11-bit "pitch number" x:
  square channels 1 and 2:  frequency = 131072 / (2048 - x)
  wave channel 3:           frequency =  65536 / (2048 - x)   (one octave lower)
So SQ_A4 is the number that makes a square channel play A4 (440 Hz), and WV_A4
the number that makes the wave channel play the same note.
"""
import os

NAMES = ["C", "CS", "D", "DS", "E", "F", "FS", "G", "GS", "A", "AS", "B"]


def main():
    lines = ["; GENERATED by art/make_notes.py - pitch numbers for musical notes.",
             "; SQ_ = square channels (1, 2), WV_ = wave channel (3). CS = C sharp."]
    for octave in range(2, 8):
        for i, name in enumerate(NAMES):
            midi = 12 * (octave + 1) + i          # A4 = 69
            freq = 440.0 * 2 ** ((midi - 69) / 12)
            sq = round(2048 - 131072 / freq)
            wv = round(2048 - 65536 / freq)
            if 0 <= sq < 2048:
                lines.append(f"DEF SQ_{name}{octave} EQU {sq}")
            if 0 <= wv < 2048:
                lines.append(f"DEF WV_{name}{octave} EQU {wv}")
    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, "..", "src", "notes.inc"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
